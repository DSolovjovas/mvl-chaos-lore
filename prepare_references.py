def copy_exact(source, destination):
    destination = destination.resolve()
    if not destination.is_relative_to(ROOT):
        raise ValueError('Destination is outside workspace.')
    payload = source.read_bytes()
    if destination.exists():
        if destination.read_bytes() != payload:
            raise ValueError('Existing reference differs; preserve it before replacement.')
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        with destination.open('xb') as handle:
            handle.write(payload)
    checksum = hashlib.sha256(payload).hexdigest()
    if hashlib.sha256(destination.read_bytes()).hexdigest() != checksum:
        raise ValueError('Reference copy verification failed.')
    return checksum


def main():
    profiles = []
    for entry in DATA:
        profile = {key: value for key, value in entry.items() if key not in ('directory', 'sheet', 'face')}
        profile['images'] = []
        folder = SOURCE / entry['directory'] / 'База' / 'Референсы'
        for role in ('sheet', 'face'):
            name = entry[role]
            source = folder / name
            relative = Path('references') / entry['id'] / name
            checksum = copy_exact(source, OUT / relative)
            record = {
                'role': role, 'path': relative.as_posix(), 'sha256': checksum,
                'source': (Path(entry['directory']) / 'База' / 'Референсы' / name).as_posix(),
                'status': 'Закреплённый локальный референс; текущие текстовые уточнения имеют приоритет.',
                'purpose': 'Узнаваемость лица/морды' if role == 'face' else 'Анатомия, пропорции, основной образ',
            }
            profile['images'].append(record)
            # Preserve original provenance notes without inventing missing prompts.
            base = name.rsplit('.', 1)[0]
            for ext in ('md', 'json'):
                options = [folder / f'{base}.{ext}', folder / f'{base}..{ext}']
                original = next((p for p in options if p.exists()), None)
                if original:
                    copy_exact(original, OUT / 'references' / entry['id'] / 'sources' / original.name)
        for part in ('База.md', 'Характер.md', 'Образ основной.md'):
            copy_exact(SOURCE / entry['directory'] / 'Описания' / part, OUT / 'references' / entry['id'] / 'sources' / part)
        copy_exact(folder / 'Назначение.md', OUT / 'references' / entry['id'] / 'sources' / 'Назначение.md')
        profiles.append(profile)
    write(OUT / 'content' / 'characters.json', json.dumps(profiles, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'characters': len(profiles), 'original_images': sum(len(p['images']) for p in profiles), 'halloween': 'awaiting user files'}, ensure_ascii=True))


if __name__ == '__main__':
    main()
